/* 一条规则都没命中时的候选（聊天贴纸用，概率压得很低） */
const NEUTRAL = ['idle', 'happy']

/** 从数组里随机取一个 */
function pickOne(arr) {
  return arr[Math.floor(Math.random() * arr.length)]
}

/**
 * 按台词判情绪，返回候选表情名数组；一条都没命中返回 null。
 * @param {string} text 台词
 * @returns {string[]|null}
 */
export function moodStickers(text) {
  const s = String(text || '')
  if (!s) return null
  for (let i = 0; i < RULES.length; i++) {
    const ks = RULES[i].k
    for (let j = 0; j < ks.length; j++) {
      if (s.indexOf(ks[j]) >= 0) return RULES[i].e
    }
  }
  return null
}

/**
 * 主页用：按台词挑一个表情，一定返回结果。
 * @param {string} text 台词
 * @param {string[]} fallback 没判出情绪时用的候选
 */
export function exprFor(text, fallback) {
  const m = moodStickers(text)
  if (m) return pickOne(m)
  const fb = (fallback && fallback.length) ? fallback : NEUTRAL
  return pickOne(fb)
}

/**
 * 聊天页用：这条消息要不要夹带贴纸，带哪一张。
 * 情绪匹配成功 → 按 chance 决定带不带（带的话一定是匹配的那几张之一）；
 * 没匹配到 → 只有 25% × chance 的概率带一张中性的，免得满屏乱贴。
 *
 * @param {string} text 台词
 * @param {number} chance 夹带概率（0~1）
 * @returns {string} 表情名，或 '' 表示不带
 */
export function stickerFor(text, chance) {
  const p = typeof chance === 'number' ? chance : 0.5
  const m = moodStickers(text)
  if (m) return Math.random() < p ? pickOne(m) : ''
  return Math.random() < p * 0.25 ? pickOne(NEUTRAL) : ''
}
