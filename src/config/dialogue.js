/**
 * 桌宠框架 · 台词库
 * ===============================================================
 * 这个应用里**所有会显示出来的文字**都集中在这个文件。
 * 想换角色？只改这个文件 + config/character.js 就够了，别处不用碰。
 *
 * ── 怎么填 ────────────────────────────────────────────────────
 * 1) 每个导出都是一个「台词池」，池子里的句子被随机抽一条显示。
 * 2) 池子里放多少条都行 —— 建议 4 条以上，不然很快就会重复。
 *    只有 1 条也能跑，只是每次都说同一句。
 * 3) 下面每段都留了 1～2 条**示例台词**（标了 `示例` 字样），
 *    照着格式替换成你自己的话即可。示例本身是能直接跑的，
 *    所以就算你什么都不改，应用也能正常启动。
 * 4) 键名（key）不能随便改 —— 它们和代码里的判断一一对应，
 *    每个对象上方都写了「谁在用它」，改 key 会导致那段台词永远不出现。
 *
 * ── 两个变量占位符 ────────────────────────────────────────────
 *   {nick}  会被替换成 config/character.js 里的 playerName（对使用者的称呼）
 *   {n}     会被替换成具体数字（目前只有连续登录天数用）
 *   例：'第 {n} 天啦，{nick} 今天也要开心哦'
 *
 * ── 文风 ──────────────────────────────────────────────────────
 *   框架不限制文风，但建议保持「同一个人说话」的一致性：
 *   句长相近、语气词统一、人称统一。冷热混着写会显得像机器人。
 * ===============================================================
 */

